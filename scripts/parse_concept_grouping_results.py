"""Parse LLM-assisted concept-grouping results.

The input is a result JSONL file generated by `scripts/run_open_coding.py`.
This script extracts the concepts and behaviour assignments returned by the
LLM, joins them to the original behaviours, and writes a review-level concept
summary and validation report.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any

import pandas as pd


DEFAULT_BEHAVIOURS_PATH = (
    "outputs/open_coding/analysis/open_coding_v0_1_n180_behaviours_flat.csv"
)
DEFAULT_RESULTS_PATH = (
    "outputs/open_coding/concept_grouping/results/"
    "open_coding_v0_1_n180_concept_grouping_v0_1_requests_results_gpt-5.5_temp0.0.jsonl"
)
DEFAULT_OUTPUT_DIR = "outputs/open_coding/concept_grouping/analysis"
DEFAULT_PREFIX = "open_coding_v0_1_n180_concept_grouping_v0_1"


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    with path.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def make_behaviour_id(row: pd.Series) -> str:
    return f"B{int(row['result_idx']):04d}_{int(row['behaviour_idx']):02d}"


def count_string(values: pd.Series, top_n: int = 8) -> str:
    counts = Counter(str(value) for value in values.dropna() if str(value).strip())
    return "; ".join(f"{key}: {value}" for key, value in counts.most_common(top_n))


def first_nonempty(values: pd.Series, n: int = 3, max_chars: int = 220) -> str:
    examples: list[str] = []
    seen: set[str] = set()
    for value in values.dropna():
        text = str(value).strip()
        if not text or text in seen:
            continue
        seen.add(text)
        if len(text) > max_chars:
            text = text[: max_chars - 3].rstrip() + "..."
        examples.append(text)
        if len(examples) >= n:
            break
    return " || ".join(examples)


def extract_results(result_rows: list[dict[str, Any]]) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    concept_rows: list[dict[str, Any]] = []
    assignment_rows: list[dict[str, Any]] = []
    uncertainty_rows: list[dict[str, Any]] = []
    validation: dict[str, Any] = {
        "result_rows": len(result_rows),
        "parsed_rows": 0,
        "parse_error_rows": 0,
        "missing_assignment_ids": {},
        "extra_assignment_ids": {},
        "duplicate_assignment_ids": {},
        "unknown_concept_assignments": {},
    }

    for row in result_rows:
        source = row.get("source", {})
        batch_id = source.get("batch_id", "")
        expected_ids = set(source.get("behaviour_ids", []))
        parsed = row.get("parsed_output_json") or {}

        if not parsed:
            validation["parse_error_rows"] += 1
            continue
        validation["parsed_rows"] += 1

        concepts = parsed.get("concepts", [])
        concept_labels = {concept.get("concept_label") for concept in concepts}
        for concept in concepts:
            concept_rows.append(
                {
                    "batch_id": batch_id,
                    "dimension_hint_batch": source.get("dimension_hint", ""),
                    "concept_label": concept.get("concept_label", ""),
                    "concept_definition": concept.get("concept_definition", ""),
                    "final_dimension_candidate": concept.get("final_dimension_candidate", ""),
                    "known_failure_link": concept.get("known_failure_link", ""),
                    "keep_decision_suggested": concept.get("keep_decision_suggested", ""),
                    "candidate_checklist_question": concept.get("candidate_checklist_question", ""),
                    "representative_behaviour_ids": "|".join(concept.get("representative_behaviour_ids", []) or []),
                    "why_these_behaviours_belong_together": concept.get("why_these_behaviours_belong_together", ""),
                }
            )

        assigned_ids: list[str] = []
        for assignment in parsed.get("assignments", []):
            behaviour_id = assignment.get("behaviour_id", "")
            concept_label = assignment.get("concept_label", "")
            assigned_ids.append(behaviour_id)
            assignment_rows.append(
                {
                    "batch_id": batch_id,
                    "dimension_hint_batch": source.get("dimension_hint", ""),
                    "behaviour_id": behaviour_id,
                    "concept_label_llm_suggested": concept_label,
                    "assignment_confidence": assignment.get("assignment_confidence", ""),
                    "assignment_rationale": assignment.get("rationale", ""),
                }
            )
            if concept_label not in concept_labels:
                validation["unknown_concept_assignments"].setdefault(batch_id, []).append(concept_label)

        assigned_set = set(assigned_ids)
        missing = sorted(expected_ids - assigned_set)
        extra = sorted(assigned_set - expected_ids)
        duplicates = sorted([item for item, count in Counter(assigned_ids).items() if count > 1])
        if missing:
            validation["missing_assignment_ids"][batch_id] = missing
        if extra:
            validation["extra_assignment_ids"][batch_id] = extra
        if duplicates:
            validation["duplicate_assignment_ids"][batch_id] = duplicates

        for idx, uncertainty in enumerate(parsed.get("uncertainties", []), start=1):
            uncertainty_rows.append(
                {
                    "batch_id": batch_id,
                    "uncertainty_idx": idx,
                    "uncertainty": str(uncertainty),
                }
            )

    return (
        pd.DataFrame(concept_rows),
        pd.DataFrame(assignment_rows),
        pd.DataFrame(uncertainty_rows),
        validation,
    )


def build_summary(assignments_joined: pd.DataFrame, concepts: pd.DataFrame) -> pd.DataFrame:
    if assignments_joined.empty:
        return pd.DataFrame()

    summary = (
        assignments_joined.groupby("concept_label_llm_suggested", dropna=False)
        .agg(
            mention_n=("concept_label_llm_suggested", "size"),
            review_n=("review_record_id", "nunique"),
            dataset_counts=("dataset", count_string),
            score_tier_counts=("score_tier", count_string),
            dimension_hint_counts=("dimension_hint", count_string),
            behaviour_type_counts=("behaviour_type", count_string),
            confidence_counts=("assignment_confidence", count_string),
            example_behaviour_labels=("behaviour_label", first_nonempty),
            example_evidence_quotes=("evidence_quote", first_nonempty),
        )
        .reset_index()
        .sort_values(["review_n", "mention_n"], ascending=False)
    )

    concept_meta = (
        concepts.groupby("concept_label", dropna=False)
        .agg(
            concept_definitions=("concept_definition", first_nonempty),
            final_dimension_candidates=("final_dimension_candidate", count_string),
            known_failure_links=("known_failure_link", count_string),
            keep_decisions_suggested=("keep_decision_suggested", count_string),
            candidate_checklist_questions=("candidate_checklist_question", first_nonempty),
        )
        .reset_index()
        .rename(columns={"concept_label": "concept_label_llm_suggested"})
    )
    return summary.merge(concept_meta, on="concept_label_llm_suggested", how="left")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Parse LLM concept-grouping results.")
    parser.add_argument("--results-path", default=DEFAULT_RESULTS_PATH, help="Concept-grouping result JSONL.")
    parser.add_argument("--behaviours-path", default=DEFAULT_BEHAVIOURS_PATH, help="Flattened-behaviours CSV.")
    parser.add_argument("--output-dir", default=DEFAULT_OUTPUT_DIR, help="Output directory.")
    parser.add_argument("--prefix", default=DEFAULT_PREFIX, help="Output filename prefix.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    results_path = Path(args.results_path)
    behaviours_path = Path(args.behaviours_path)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    result_rows = read_jsonl(results_path)
    behaviours = pd.read_csv(behaviours_path)
    behaviours["behaviour_id"] = behaviours.apply(make_behaviour_id, axis=1)

    concepts, assignments, uncertainties, validation = extract_results(result_rows)
    assignments_joined = assignments.merge(behaviours, on="behaviour_id", how="left")
    summary = build_summary(assignments_joined, concepts)

    concepts_path = output_dir / f"{args.prefix}_llm_concepts.csv"
    assignments_path = output_dir / f"{args.prefix}_llm_assignments.csv"
    summary_path = output_dir / f"{args.prefix}_llm_concept_summary.csv"
    uncertainties_path = output_dir / f"{args.prefix}_llm_uncertainties.csv"
    validation_path = output_dir / f"{args.prefix}_validation.json"
    manual_path = output_dir / f"{args.prefix}_manual_workspace.csv"

    concepts.to_csv(concepts_path, index=False)
    assignments_joined.to_csv(assignments_path, index=False)
    summary.to_csv(summary_path, index=False)
    uncertainties.to_csv(uncertainties_path, index=False)

    manual = assignments_joined.copy()
    manual["concept_label_final"] = manual["concept_label_llm_suggested"]
    manual["final_dimension"] = manual.get("dimension_hint", "")
    manual["keep_decision_final"] = ""
    manual["manual_check_note"] = ""
    if not manual_path.exists():
        manual.to_csv(manual_path, index=False)

    validation.update(
        {
            "concepts": len(concepts),
            "assignments": len(assignments),
            "assignments_joined": len(assignments_joined),
            "unmatched_behaviour_rows": int(assignments_joined["review_record_id"].isna().sum())
            if not assignments_joined.empty
            else 0,
            "unique_concept_labels": int(summary["concept_label_llm_suggested"].nunique())
            if not summary.empty
            else 0,
        }
    )
    validation_path.write_text(json.dumps(validation, indent=2, ensure_ascii=False), encoding="utf-8")

    print(
        json.dumps(
            {
                "results_path": str(results_path),
                "concepts_path": str(concepts_path),
                "assignments_path": str(assignments_path),
                "summary_path": str(summary_path),
                "validation_path": str(validation_path),
                "manual_path": str(manual_path),
                **validation,
            },
            indent=2,
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
